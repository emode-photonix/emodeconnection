def _server(em: Any) -> Any:
    return ui.ensure_server(em)


def _http(
    server: Any, method: str, path: str, body: Optional[Dict[str, Any]] = None, headers: Optional[Dict[str, str]] = None
) -> tuple:
    conn = http.client.HTTPConnection("127.0.0.1", server.port, timeout=10)
    sent = {"Host": f"127.0.0.1:{server.port}", "X-EMode-Token": server.token, "Content-Type": "application/json"}
    sent.update(headers or {})
    sent = {k: v for k, v in sent.items() if v is not None}
    conn.request(method, path, body=json.dumps(body).encode() if body is not None else None, headers=sent)
    response = conn.getresponse()
    payload = response.read()
    conn.close()
    return response.status, (json.loads(payload) if payload else None)


def bench(em: Any, controls: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """What the tab gets when it posts `controls` to the workbench."""
    status, reply = _http(
        _server(em), "POST", "/api/views/bench/data", {"controls": controls or {}, "pixels": [1170, 720], "width": 585}
    )
    assert status == 200
    return reply


def _calls(em: Any, function: str) -> List[Dict[str, Any]]:
    return em.client.calls(function)


def _xs(trace: Dict[str, Any]) -> List[float]:
    """A trace's x values, sent as a list or as Plotly's typed array."""
    import base64

    x = trace["x"]
    if isinstance(x, dict):
        return np.frombuffer(base64.b64decode(x["bdata"]), dtype=np.dtype(x["dtype"])).tolist()
    return list(x)


